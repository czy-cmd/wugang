parent = {}
order = []
def dfs(nid, stack):
    if nid in end_ids:
        return
    if nid in stack:
        chk("无环", False, nid); return
    stack.add(nid)
    order.append(nid)
    for c in nodes[nid]["choices"]:
        t = c[1]
        if t in parent and parent[t] != nid:
            chk("严格树", False, f"{t} 双父")
        parent[t] = nid
        if t in node_ids:
            dfs(t, stack)
    stack.discard(nid)

dfs("0", set())
chk("所有节点可达", len(order) == len(node_ids), f"{len(order)}/{len(node_ids)}")

label_of = {}
for nid, n in nodes.items():
    for c in n["choices"]:
        label_of[(nid, c[1])] = c[0]

def path_of(eid):
    chain = []
    cur = eid
    while cur != "0":
        p = parent[cur]
        chain.append(label_of[(p, cur)])
        cur = p
    chain.reverse()
    return chain

